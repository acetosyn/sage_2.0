"""Compile current desktop foundations into an explicit, overridable cascade.

Mobile reads the original files unchanged. Desktop keeps legacy normal and
priority declarations in separate normal layers, then the new component layer.
No old build or external stylesheet is used. Run after editing a source below.
"""
from pathlib import Path
import hashlib,json
import tinycss2

ROOT=Path(__file__).resolve().parents[1]
SOURCES=['vision','dashboard','control','premium','market','business','sage5']

def compact(tokens):
    return tinycss2.serialize([t for t in tokens if t.type!='comment']).strip()

def split_rules(rules,priority):
    out=[]
    for rule in rules:
        if rule.type=='qualified-rule':
            declarations=tinycss2.parse_declaration_list(rule.content,skip_whitespace=True,skip_comments=True)
            chosen=[]
            for declaration in declarations:
                if declaration.type=='declaration' and declaration.important==priority:
                    chosen.append(declaration.name+':'+compact(declaration.value)+';')
            if chosen:out.append(compact(rule.prelude)+'{'+''.join(chosen)+'}')
        elif rule.type=='at-rule':
            prelude=compact(rule.prelude);head='@'+rule.at_keyword+(' '+prelude if prelude else '')
            if rule.content is None:
                if not priority and rule.lower_at_keyword!='charset':out.append(head+';')
            elif rule.lower_at_keyword in ['media','supports','container','layer']:
                inside=split_rules(tinycss2.parse_rule_list(rule.content,skip_comments=True,skip_whitespace=True),priority)
                if inside:out.append(head+'{'+inside+'}')
            elif not priority:out.append(head+'{'+compact(rule.content)+'}')
    return ''.join(out)

def build_bundle(suffix,sources):
    parsed=[];manifest={}
    for name in sources:
        path=ROOT/'static/css'/f'{name}.css';source=path.read_text(encoding='utf-8-sig');manifest[path.relative_to(ROOT).as_posix()]=hashlib.sha256(path.read_bytes()).hexdigest();parsed.extend(tinycss2.parse_stylesheet(source,skip_comments=True,skip_whitespace=True))
    css='/* Generated by tools/build_desktop_styles.py from the current approved source. */\n@layer sage-foundation,sage-foundation-priority,sage-desktop;\n@media(min-width:901px){\n@layer sage-foundation{'+split_rules(parsed,False)+'}\n@layer sage-foundation-priority{'+split_rules(parsed,True)+'}\n}\n'
    target=ROOT/f'static/css/desktop_foundation{suffix}.css';target.write_text(css,encoding='utf-8');(ROOT/f'static/css/desktop_foundation{suffix}.sources.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8');print(f'Desktop foundation: {target.stat().st_size:,} bytes from {len(sources)} current stylesheets')
def build():
    for suffix,sources in [('',SOURCES),('_auth',['vision']),('_register',['vision','market']),('_platform',['vision','platform_console'])]:build_bundle(suffix,sources)
if __name__=='__main__':build()
