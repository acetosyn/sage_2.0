"""Rebuild after editing source CSS. Build-time dependency: pip install tinycss2."""
from pathlib import Path
import tinycss2

ROOT = Path(__file__).resolve().parents[1] / "static" / "css"
GROUPS = [
    ("(max-width:900px)", ["vision", "dashboard", "control", "premium", "market", "business", "sage5"]),
    ("(min-width:901px)", ["desktop_foundation", "sage_desktop"]),
]

def build():
    # Keep original ordering, cascade layers and relative asset paths.
    parts = ["/* SAGE RESPONSIVE FOUNDATION — generated by scripts/build_workspace_responsive.py. */"]
    for media, names in GROUPS:
        parts.append("@media " + media + " {")
        for name in names:
            source = (ROOT / (name + ".css")).read_text()
            if "@import " in source or "@charset " in source:
                raise ValueError("Hoist CSS imports/charset before bundling: " + name)
            # Serialize each sheet separately, preserving browser EOF block recovery.
            # Otherwise an unclosed legacy block can swallow the next source.
            source = tinycss2.serialize(tinycss2.parse_stylesheet(source))
            parts.extend(["/* SOURCE: " + name + ".css */", source])
        parts.append("}")
    (ROOT / "workspace_responsive.css").write_text("\n".join(parts) + "\n")

if __name__ == "__main__":
    build()
